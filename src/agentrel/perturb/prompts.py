"""Prompt perturbation: run the same tasks with semantically equivalent wording.

Paraphrases keep the task id and correct answer, only the prompt changes, so
results stay comparable with the baseline. Paraphrases can be hand-written or
generated by an LLM (the paper used 5 per task).
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence

from agentrel.core.runner import Task


def paraphrased_tasks(
    tasks: Sequence[Task], paraphrases: Mapping[str, Sequence[str]]
) -> list[Task]:
    """One new Task per paraphrase. Tasks without paraphrases are skipped."""
    out: list[Task] = []
    for task in tasks:
        for prompt in paraphrases.get(task.id, []):
            out.append(task.model_copy(update={"prompt": prompt}))
    return out
